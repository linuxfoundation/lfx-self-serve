// Rebuild scripts/frontend-test-durations.json from one Quality Checks run's Frontend Tests
// shard logs (#5980). Read-only unless --write is passed.
//
//   node scripts/refresh-test-durations.mjs --run <run-id> [--write]
//   node scripts/refresh-test-durations.mjs --logs <dir-of-job-logs> [--write]
//
// --write-budget-baseline also rewrites scripts/spec-budget-baseline.json from the same run.
// That loosens the ratchet, so do it only when resetting the budget on purpose.

import { execFileSync } from 'node:child_process';
import { appendFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { discoverSpecs } from './lib/app-test-shards.mjs';
import { buildSpecBudgetBaseline } from './lib/check-spec-budget.mjs';
import { buildTestDurations, DRIFT_THRESHOLD, weightDrift } from './lib/refresh-test-durations.mjs';
import { attachSpecPaths, parseVitestFileLines } from './lib/spec-timings.mjs';

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DURATIONS = join(APP_ROOT, 'scripts/frontend-test-durations.json');
const BASELINE = join(APP_ROOT, 'scripts/spec-budget-baseline.json');
const REPO = process.env.GITHUB_REPOSITORY || 'linuxfoundation/lfx-self-serve';

try {
  const args = process.argv.slice(2);
  const option = (name) => {
    const at = args.indexOf(name);
    return at === -1 ? undefined : args[at + 1];
  };
  const runId = option('--run');
  const logsDir = option('--logs');
  if (Boolean(runId) === Boolean(logsDir)) throw new Error('Pass exactly one of --run <run-id> or --logs <dir>.');
  if (runId && !/^\d+$/.test(runId)) throw new Error('--run takes a numeric workflow run id.');

  const { logs, source, sha } = runId ? fetchRunLogs(runId) : readLogDir(resolve(logsDir));
  const parsed = logs.flatMap((text) => parseVitestFileLines(text));
  const { matched, unknown } = attachSpecPaths(parsed, discoverSpecs(join(APP_ROOT, 'src/app'), APP_ROOT));
  if (matched.length === 0) throw new Error('No per-file timings found in the logs. Did the Vitest output format change?');
  if (unknown.length > 0) console.log(`[durations] ignoring ${unknown.length} spec(s) no longer in src/app: ${unknown.join(', ')}`);

  const current = JSON.parse(readFileSync(DURATIONS, 'utf8'));
  const files = buildTestDurations(matched);
  const drift = weightDrift(current.files, files);
  const drifted = drift > DRIFT_THRESHOLD;
  console.log(
    `[durations] ${matched.length} spec timings, ${Object.keys(files).length} at 3s or more; weights moved ${(drift * 100).toFixed(1)}% ` +
      `(${drifted ? 'over' : 'within'} the ${DRIFT_THRESHOLD * 100}% threshold).`
  );
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `drift=${drift.toFixed(3)}\ndrifted=${drifted}\n`);

  if (args.includes('--write')) {
    const note = `Seconds of test time for every spec that ran for 3s or longer in the source run${sha ? ` (main at ${sha.slice(0, 10)})` : ''}, rounded to 0.1s. Regenerated by scripts/refresh-test-durations.mjs.`;
    writeFileSync(DURATIONS, `${JSON.stringify({ source, note, files }, null, 2)}\n`);
    console.log(`[durations] wrote ${relative(process.cwd(), DURATIONS)}`);
  }
  if (args.includes('--write-budget-baseline')) {
    const note = `Spec files over the runtime budget in the source run, at their measured time plus 25% headroom. A listed file fails only if it gets slower than this. See docs/architecture/testing/unit-testing.md.`;
    writeFileSync(BASELINE, `${JSON.stringify({ source, note, files: buildSpecBudgetBaseline(matched) }, null, 2)}\n`);
    console.log(`[durations] wrote ${relative(process.cwd(), BASELINE)}`);
  }
} catch (error) {
  console.error(`[durations] ${error.message}`);
  process.exitCode = 1;
}

function gh(...args) {
  return execFileSync('gh', ['api', ...args], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
}

/** Every Frontend Tests job of the run must have passed, or the weights would miss whole shards. */
function fetchRunLogs(runId) {
  const run = JSON.parse(gh(`repos/${REPO}/actions/runs/${runId}`));
  const jobs = gh('--paginate', `repos/${REPO}/actions/runs/${runId}/jobs?per_page=100`, '--jq', '.jobs[] | select(.name | startswith("Frontend Tests")) | [.id, .conclusion] | @tsv')
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('\t'));
  if (jobs.length === 0) throw new Error(`Run ${runId} has no Frontend Tests jobs.`);
  const failed = jobs.filter(([, conclusion]) => conclusion !== 'success');
  if (failed.length > 0) throw new Error(`Run ${runId} has ${failed.length} Frontend Tests job(s) that did not succeed; use a green run.`);
  return { logs: jobs.map(([id]) => gh(`repos/${REPO}/actions/jobs/${id}/logs`)), source: run.html_url, sha: run.head_sha };
}

function readLogDir(directory) {
  const names = readdirSync(directory).filter((name) => name.endsWith('.log') || name.endsWith('.txt'));
  if (names.length === 0) throw new Error(`No .log or .txt files in ${directory}.`);
  return { logs: names.map((name) => readFileSync(join(directory, name), 'utf8')), source: `local logs (${names.length} files)`, sha: undefined };
}

