/*
 * Pure transform from the LFX UI Library's `tokens.json` to the `ui-tokens.css` custom properties.
 * Kept free of file I/O so the drift spec can regenerate the stylesheet and compare it to the committed one.
 */

const THEMES = ['light', 'dark'];

/**
 * Custom-property name for a token. Every name carries the `--ui-` prefix (role colours already start with `ui-`),
 * so the library's `--spacing-6`, `--font-display` and the like cannot collide with app CSS.
 * Any character outside `[A-Za-z0-9_-]` (e.g. the dot in `spacing-0.5`) is backslash-escaped, backslashes included.
 */
export function varName(name) {
  return `--${name.startsWith('ui-') ? '' : 'ui-'}${name.replace(/[^A-Za-z0-9_-]/g, (c) => `\\${c}`)}`;
}

/** Resolves a `{azure-500}` reference to `var(--ui-azure-500)`; any other value is already a literal. */
export function resolveValue(value) {
  return value.replace(/\{([^}]+)\}/g, (_, ref) => `var(${varName(ref)})`);
}

function declarations(tokens, theme) {
  return tokens.map((token) => {
    const value = typeof token.value === 'string' ? token.value : token.value[theme];
    return `  ${varName(token.name)}: ${resolveValue(value)};`;
  });
}

const isThemed = (token) => typeof token.value === 'object';

/** Builds the full stylesheet text from parsed `tokens.json`. */
export function buildUiTokensCss(tokens) {
  const colors = tokens.color.tokens;
  const shadows = tokens.shadow.tokens;
  const fonts = Object.entries(tokens.type.families).map(([key, stack]) => `  ${varName(`font-${key}`)}: ${stack};`);
  const fixed = [
    ...colors.filter((t) => !isThemed(t)),
    ...tokens.spacing.tokens,
    ...tokens.radius.tokens,
    ...tokens.height.tokens,
    ...tokens.width.tokens,
    ...tokens.zIndex.tokens,
    ...tokens.breakpoint.tokens,
    ...tokens.opacity.tokens,
  ];
  const themed = [...colors, ...shadows].filter(isThemed);
  const themedFor = (theme) => themed.filter((t) => t.value[theme] !== undefined);

  const [light, dark] = THEMES;
  return [
    '/* Copyright The Linux Foundation and each contributor to LFX. */',
    '/* SPDX-License-Identifier: MIT */',
    '',
    '/* GENERATED by scripts/build-ui-tokens.mjs from scripts/ui-tokens/tokens.json. Do not edit; run `yarn ui:tokens`. */',
    '',
    ':root {',
    ...fonts,
    ...declarations(fixed),
    '}',
    '',
    `:root,\n[data-theme='${light}'] {`,
    ...declarations(themedFor(light), light),
    '}',
    '',
    `[data-theme='${dark}'] {`,
    ...declarations(themedFor(dark), dark),
    '}',
    '',
  ].join('\n');
}
